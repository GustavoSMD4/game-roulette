import sqlite3

conn = sqlite3.Connection("server/database/database.db", check_same_thread=False)
cursor = conn.cursor()

def createTable():
    cursor.execute("""
         CREATE TABLE IF NOT EXISTS USUARIOS(
	ID INTEGER PRIMARY KEY AUTOINCREMENT,
  	USUARIO VARCHAR(100) NOT NULL UNIQUE,
  	SENHA VARCHAR(100) NOT NULL,
  	SALDO DECIMAL(10, 2) NOT NULL DEFAULT 0
)          
                   """)
    
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS BLACKJACK (
    	ID VARCHAR(36) NOT NULL PRIMARY KEY UNIQUE,
		JOGADOR_HOST INTEGER
		);
 	""")
    
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS JOGADOR_BLACKJACK (
    	ID VARCHAR(36) NOT NULL PRIMARY KEY UNIQUE,
  		ID_JOGO VARCHAR(36) NOT NULL,
    	NOME VARCHAR(100) NOT NULL,
    	VALOR_MAO INTEGER NOT NULL DEFAULT 0,
  		CONSTRAINT FK_JOGADOR_JOGO FOREIGN KEY (ID_JOGO) REFERENCES BLACKJACK(ID)
);
    """)
    
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS CARTA_JOGADOR_BLACKJACK (
    	ID VARCHAR(36) NOT NULL PRIMARY KEY UNIQUE,
    	ID_JOGO VARCHAR(36) NOT NULL,
    	ID_JOGADOR INTEGER NOT NULL,
  		RANK VARCHAR(1) NOT NULL,
  		SUIT VARCHAR(7) NOT NULL,
  		VALOR INTEGER NOT NULL,
    	CONSTRAINT FK_CARTA_JOGO FOREIGN KEY (ID_JOGO) REFERENCES BLACKJACK(ID),
    	CONSTRAINT FK_CARTA_JOGADOR FOREIGN KEY (ID_JOGADOR) REFERENCES JOGADOR_BLACKJACK(ID)
		);   
    """)
    
    cursor.execute("""
		CREATE TABLE IF NOT EXISTS RESULTADOS_ROLETA (
			ID_JOGADOR TEXT NOT NULL,
			APOSTA_JOGADOR TEXT NOT NULL,
			VALOR_APOSTA REAL NOT NULL,
			RESULTADO TEXT NOT NULL,
			VALOR_RESULTADO REAL NOT NULL,
			GANHOU INTEGER NOT NULL,
			DATA_HORA TIMESTAMP DEFAULT CURRENT_TIMESTAMP
		);         
    """)


cursor.execute("PRAGMA foreign_keys = ON;")    
createTable()

conn.commit()
conn.close()